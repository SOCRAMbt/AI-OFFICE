/**
 * Report Card — tarjeta compartible de resultados de una corrida.
 *
 * Genera un resumen visual de lo que pasó en la corrida:
 * - Tareas completadas vs total
 * - Mentiras atrapadas (agent said "done" but tests failed)
 * - Gates pasados/fallados
 * - Agentes usados
 * - Duración
 *
 * Incluye texto pre-armado para compartir en redes sociales.
 */

import fs from "node:fs/promises"
import path from "node:path"
import type { OfficeState } from "./types.js"

export interface ReportCard {
  runId: string
  objective: string
  tasksTotal: number
  tasksDone: number
  liesCaught: number
  gatesPassed: number
  gatesFailed: number
  agentsUsed: number
  duration: string
  shareText: string
}

function countLies(state: OfficeState): number {
  let lies = 0
  for (const card of Object.values(state.cards)) {
    if (!card || typeof card !== "object") continue
    const c = card as unknown as Record<string, unknown>
    const st = c.state as string
    if (st === "blocked_escalated") {
      lies += 1
      continue
    }
    if (st === "done" && ((Number(c.rejections) || 0) > 0 || (Number(c.attempts) || 0) > 1)) {
      lies += 1
    }
  }
  return lies
}

function countGates(state: OfficeState): { passed: number; failed: number } {
  let passed = 0
  let failed = 0
  for (const card of Object.values(state.cards)) {
    if (!card || typeof card !== "object") continue
    const c = card as unknown as Record<string, unknown>
    const attempts = Number(c.attempts) || 0
    const rejections = Number(c.rejections) || 0
    if (attempts > 0) {
      passed += attempts - rejections
      failed += rejections
    }
  }
  return { passed, failed }
}

function formatDuration(state: OfficeState): string {
  const created = new Date(state.createdAt).getTime()
  const updated = new Date(state.updatedAt).getTime()
  const diffMs = updated - created
  const mins = Math.floor(diffMs / 60000)
  if (mins < 60) return `${mins}m`
  const hours = Math.floor(mins / 60)
  const remMins = mins % 60
  return `${hours}h ${remMins}m`
}

export async function generateReportCard(state: OfficeState, projectRoot: string): Promise<ReportCard> {
  const cards = Object.values(state.cards)
  const tasksTotal = cards.length
  const tasksDone = cards.filter((c) => (c as unknown as Record<string, unknown>).state === "done").length
  const liesCaught = countLies(state)
  const { passed: gatesPassed, failed: gatesFailed } = countGates(state)
  const agentsUsed = Object.keys(state.sessions || {}).length || Object.keys({}).length
  const duration = formatDuration(state)

  const shareText = `AI-OFFICE caught ${liesCaught} lies this run. The agent said "done" ${tasksDone} times — ${liesCaught} had broken tests. All caught. 🎯\n\nhttps://github.com/SOCRAMbt/AI-OFFICE`

  const card: ReportCard = {
    runId: state.runId,
    objective: state.objective,
    tasksTotal,
    tasksDone,
    liesCaught,
    gatesPassed,
    gatesFailed,
    agentsUsed,
    duration,
    shareText,
  }

  // Save to .oficina/report-card.md
  const officeDir = path.join(projectRoot, ".oficina")
  try {
    await fs.mkdir(officeDir, { recursive: true })
    const md = `# Report Card — ${state.runId}

## Objective
${state.objective}

## Results
- **Tasks:** ${tasksDone}/${tasksTotal} completed
- **Lies caught:** ${liesCaught} (agent said "done" with broken tests)
- **Gates:** ${gatesPassed} passed, ${gatesFailed} failed
- **Duration:** ${duration}

## Share
${shareText}

---
*Generated by AI-OFFICE — your AI agent says "done". AI-OFFICE makes it prove it.*
`
    await fs.writeFile(path.join(officeDir, "report-card.md"), md, "utf8")
  } catch {
    // Non-critical: don't fail if we can't write
  }

  return card
}

export function formatReportCard(card: ReportCard): string {
  const lines: string[] = []
  lines.push(`\n📊 Report Card — ${card.runId}\n`)
  lines.push(`  Objective: ${card.objective}`)
  lines.push(`  Tasks: ${card.tasksDone}/${card.tasksTotal} completed`)
  lines.push(`  Lies caught: ${card.liesCaught}`)
  lines.push(`  Gates: ${card.gatesPassed} passed, ${card.gatesFailed} failed`)
  lines.push(`  Duration: ${card.duration}`)
  lines.push(`\n  Share: ${card.shareText}\n`)
  return lines.join("\n")
}